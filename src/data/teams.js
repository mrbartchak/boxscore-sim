let _id = 0;
export const TEAMS = [];
export const CONFERENCES = Object.keys(RAW);

for (const conf of CONFERENCES) {
  for (const [name, abbr, prestige, color] of RAW[conf]) {
    TEAMS.push({
      id: `t${_id++}`,
      name,
      abbr,
      conference: conf,
      prestige,
      color,
    });
  }
}

export const TEAMS_BY_ID = Object.fromEntries(TEAMS.map((t) => [t.id, t]));
export const teamsByConference = () =>
  CONFERENCES.map((conf) => ({
    conference: conf,
    teams: TEAMS.filter((t) => t.conference === conf),
  }));
